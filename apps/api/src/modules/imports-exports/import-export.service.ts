import archiver from 'archiver';
import AdmZip from 'adm-zip';
import path from 'path';
import { prisma } from '../../config/db';
import { NotFoundError, BadRequestError } from '../../utils/errors';
import { slugify, sanitizeFileName } from '@devblueprint/shared';
import { DocumentStatus } from '@prisma/client';

export class ImportExportService {
  async getSingleDocExport(documentId: string) {
    const doc = await prisma.document.findUnique({
      where: { id: documentId },
      include: {
        category: true,
        project: true
      }
    });

    if (!doc) throw new NotFoundError('Document not found');

    const fileName = doc.fileName.endsWith('.md') ? doc.fileName : `${doc.fileName}.md`;
    return {
      fileName,
      content: doc.content
    };
  }

  async exportProjectZip(projectId: string, outputStream: NodeJS.WritableStream) {
    const project = await prisma.project.findUnique({
      where: { id: projectId },
      include: {
        categories: {
          orderBy: { sortOrder: 'asc' },
          include: {
            documents: {
              where: { isArchived: false },
              orderBy: { sortOrder: 'asc' }
            }
          }
        }
      }
    });

    if (!project) throw new NotFoundError('Project not found');

    const archive = archiver('zip', { zlib: { level: 9 } });
    archive.pipe(outputStream);

    // 1. Generate master INDEX.md
    let indexContent = `# ${project.name} - Technical Blueprint & Documentation Index\n\n`;
    indexContent += `> Generated by DevBlueprint on ${new Date().toISOString()}\n\n`;
    if (project.description) {
      indexContent += `## Overview\n${project.description}\n\n`;
    }
    indexContent += `**Type:** ${project.projectType}  \n`;
    indexContent += `**Category:** ${project.category}  \n`;
    try {
      const tech = JSON.parse(project.techStack);
      if (Array.isArray(tech) && tech.length > 0) {
        indexContent += `**Tech Stack:** ${tech.join(', ')}  \n`;
      }
    } catch {
      // ignore
    }
    indexContent += `\n---\n\n## Table of Contents\n\n`;

    // 2. Add files per category
    for (const cat of project.categories) {
      const isRoot = cat.slug === 'root';
      const folderName = isRoot ? '' : sanitizeFileName(cat.slug || slugify(cat.name));
      const displayPath = isRoot ? './' : `./docs/${folderName}/`;
      indexContent += `### ${cat.name} (\`${displayPath}\`)\n`;

      if (cat.documents.length === 0) {
        indexContent += `*(No documents in this category)*\n\n`;
      } else {
        for (const doc of cat.documents) {
          const rawFileName = doc.fileName || `${slugify(doc.title).toUpperCase().replace(/-/g, '_')}.md`;
          const fileName = rawFileName.endsWith('.md') ? rawFileName : `${rawFileName}.md`;
          const filePath = isRoot ? fileName : `docs/${folderName}/${fileName}`;

          archive.append(doc.content, { name: filePath });
          indexContent += `- [${doc.title}](./${filePath}) - *Status: ${doc.status}*\n`;
        }
        indexContent += `\n`;
      }
    }

    archive.append(indexContent, { name: 'INDEX.md' });
    await archive.finalize();
  }

  async exportCategoryZip(categoryId: string, outputStream: NodeJS.WritableStream) {
    const category = await prisma.category.findUnique({
      where: { id: categoryId },
      include: {
        documents: {
          where: { isArchived: false },
          orderBy: { sortOrder: 'asc' }
        }
      }
    });

    if (!category) throw new NotFoundError('Category not found');

    const archive = archiver('zip', { zlib: { level: 9 } });
    archive.pipe(outputStream);

    const folderName = sanitizeFileName(category.slug || slugify(category.name));
    for (const doc of category.documents) {
      const rawFileName = doc.fileName || `${slugify(doc.title).toUpperCase().replace(/-/g, '_')}.md`;
      const fileName = rawFileName.endsWith('.md') ? rawFileName : `${rawFileName}.md`;
      archive.append(doc.content, { name: `${folderName}/${fileName}` });
    }

    await archive.finalize();
  }

  async importMarkdownFiles(
    projectId: string,
    categoryId: string,
    userId: string,
    files: Array<{ originalname: string; buffer: Buffer }>
  ) {
    const createdDocs: any[] = [];

    for (const file of files) {
      const fileName = sanitizeFileName(file.originalname);
      const title = fileName.replace(/\.(md|markdown|mdx)$/i, '').replace(/[-_]/g, ' ');
      const content = file.buffer.toString('utf-8');

      const doc = await prisma.document.create({
        data: {
          projectId,
          categoryId,
          title,
          fileName,
          slug: slugify(title),
          content,
          status: DocumentStatus.DRAFT,
          createdById: userId,
          versionNumber: 1
        }
      });

      await prisma.documentVersion.create({
        data: {
          documentId: doc.id,
          versionNumber: 1,
          title: doc.title,
          content: doc.content,
          changeSummary: 'Imported from ' + fileName,
          authorId: userId
        }
      });

      createdDocs.push(doc);
    }

    return createdDocs;
  }

  async importZipArchive(
    projectId: string,
    userId: string,
    zipBuffer: Buffer
  ) {
    const zip = new AdmZip(zipBuffer);
    const entries = zip.getEntries();
    const createdCategories: Map<string, string> = new Map();
    const importedDocs: any[] = [];

    // Ensure project exists
    const project = await prisma.project.findUnique({ where: { id: projectId } });
    if (!project) throw new NotFoundError('Project not found');

    for (const entry of entries) {
      if (entry.isDirectory) continue;

      // Safe path checking to prevent zip-slip directory traversal
      const safeEntryPath = path.normalize(entry.entryName).replace(/^(\.\.(\/|\\|$))+/, '');
      if (safeEntryPath.includes('..')) continue;

      const ext = path.extname(safeEntryPath).toLowerCase();
      if (!['.md', '.markdown', '.mdx'].includes(ext)) {
        continue;
      }

      const pathParts = safeEntryPath.split(/[\/\\]/);
      let categoryName = 'Project Root';
      let categorySlug = 'root';

      if (pathParts.length === 1) {
        // Root file
        categoryName = 'Project Root';
        categorySlug = 'root';
      } else if (pathParts[0].toLowerCase() === 'docs' && pathParts.length >= 3) {
        const catFolder = pathParts[1];
        categorySlug = slugify(catFolder);
        categoryName = catFolder.replace(/^[0-9]+[-_.]\s*/, '').replace(/[-_]/g, ' ');
        categoryName = categoryName.charAt(0).toUpperCase() + categoryName.slice(1);
      } else {
        const catFolder = pathParts[0];
        categorySlug = slugify(catFolder);
        categoryName = catFolder.replace(/^[0-9]+[-_.]\s*/, '').replace(/[-_]/g, ' ');
        categoryName = categoryName.charAt(0).toUpperCase() + categoryName.slice(1);
      }

      const fileName = path.basename(safeEntryPath);
      const title = fileName.replace(/\.(md|markdown|mdx)$/i, '').replace(/[-_]/g, ' ');
      const content = entry.getData().toString('utf-8');

      // Find or create category
      let categoryId = createdCategories.get(categorySlug);
      if (!categoryId) {
        let cat = await prisma.category.findFirst({
          where: {
            projectId,
            OR: [
              { slug: categorySlug },
              { name: { equals: categoryName, mode: 'insensitive' } }
            ]
          }
        });

        if (!cat) {
          cat = await prisma.category.create({
            data: {
              projectId,
              name: categoryName,
              slug: categorySlug,
              isCustom: true
            }
          });
        }
        categoryId = cat.id;
        createdCategories.set(categorySlug, categoryId);
      }

      const doc = await prisma.document.create({
        data: {
          projectId,
          categoryId,
          title,
          fileName,
          slug: slugify(title),
          content,
          status: DocumentStatus.DRAFT,
          createdById: userId,
          versionNumber: 1
        }
      });

      await prisma.documentVersion.create({
        data: {
          documentId: doc.id,
          versionNumber: 1,
          title: doc.title,
          content: doc.content,
          changeSummary: 'Imported from ZIP archive',
          authorId: userId
        }
      });

      importedDocs.push(doc);
    }

    return {
      importedCount: importedDocs.length,
      categoriesCount: createdCategories.size
    };
  }
}

export const importExportService = new ImportExportService();

